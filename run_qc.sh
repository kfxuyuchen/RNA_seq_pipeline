#!/bin/bash
# Build QC tables + optional MultiQC report for an RNA-seq dual-pipeline outdir.
set -euo pipefail

PIPELINE_DIR="$(cd "$(dirname "$0")" && pwd)"
VERSION="1.1.0-qc"
outdir="10.qc"
work_root="."
run_multiqc=1
title="RNA-seq pipeline QC"
min_assigned=50
min_hisat2=0
force_mq=0

usage() {
  cat <<EOF
QC / MultiQC aggregator v${VERSION}

在定量输出目录下汇总比对 flagstat 与 featureCounts assignment，并可选跑 MultiQC。

Usage:
  $(basename "$0") [options]

Options:
  -o, --outdir DIR       QC 输出目录 (默认: 10.qc)
  -C, --workdir DIR      流水线结果根目录 (默认: 当前目录)
  --title STR            MultiQC 报告标题
  --min-assigned PCT     Assigned% 告警阈值 (默认: ${min_assigned})
  --min-hisat2 PCT       hisat2 overall% 告警阈值 (默认: ${min_hisat2}=关闭)
  --no-multiqc           只写 TSV，不跑 MultiQC
  --force-multiqc        MultiQC --force
  -h, --help             本帮助

输入（相对 -C）:
  08.align_stats/*.flagstat.txt
  08.align_stats/hisat2_alignment_rates.tsv
  09.featureCounts/gene_counts.txt.summary

输出:
  10.qc/align_flagstat_summary.tsv
  10.qc/hisat2_alignment_rates.tsv
  10.qc/featurecounts_summary.tsv
  10.qc/qc_overview.tsv
  10.qc/multiqc_report.html          (若安装了 multiqc)
  10.qc/multiqc_config.yaml

示例:
  cd /path/to/rnaseq_quant_XXX
  bash $PIPELINE_DIR/run_qc.sh
  bash $PIPELINE_DIR/run_qc.sh --no-multiqc
  bash $PIPELINE_DIR/run_qc.sh -C /path/to/outdir --title "SRP585076 T2T"
EOF
  exit 1
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    -o|--outdir) outdir="$2"; shift 2 ;;
    -C|--workdir) work_root="$2"; shift 2 ;;
    --title) title="$2"; shift 2 ;;
    --min-assigned) min_assigned="$2"; shift 2 ;;
    --min-hisat2) min_hisat2="$2"; shift 2 ;;
    --no-multiqc) run_multiqc=0; shift ;;
    --force-multiqc) force_mq=1; shift ;;
    -h|--help) usage ;;
    *) echo "未知选项: $1" >&2; usage ;;
  esac
done

work_root=$(cd "$work_root" && pwd)
cd "$work_root"
mkdir -p "$outdir"

echo "=== QC v${VERSION} ==="
echo "workdir=$work_root"
echo "outdir=$outdir  multiqc=$run_multiqc"

python3 "$PIPELINE_DIR/summarize_qc.py" \
  -o "$outdir" \
  --align-dir 08.align_stats \
  --fc-summary 09.featureCounts/gene_counts.txt.summary \
  --min-assigned-pct "$min_assigned" \
  --min-hisat2-pct "$min_hisat2"

cfg="${outdir}/multiqc_config.yaml"
cat > "$cfg" <<EOF
title: "${title}"
subtitle: "HISAT2 unique BAM + featureCounts"
intro_text: "Auto-generated by RNA_seq_pipeline/run_qc.sh"
show_analysis_paths: false
extra_fn_clean_exts:
  - "_sorted"
  - "_clean"
  - ".bam"
  - "_raw"
  - "_unique"
module_order:
  - samtools
  - featurecounts
table_cond_formatting_rules:
  percent_assigned:
    fail: [{lt: 40}]
    warn: [{lt: 60}]
ai_summary: false
EOF

if [[ "$run_multiqc" -eq 1 ]]; then
  if command -v multiqc >/dev/null 2>&1; then
    mq_args=(-o "$outdir" -c "$cfg" -n multiqc_report --verbose)
    [[ "$force_mq" -eq 1 ]] && mq_args+=(--force)
    # Prefer modules that exist; MultiQC ignores missing data
    echo -e "\n=== MultiQC ==="
    multiqc \
      08.align_stats \
      09.featureCounts \
      "$outdir" \
      "${mq_args[@]}" \
      || echo "WARN: multiqc exited non-zero (report may still be partial)"
    echo "MultiQC report: ${outdir}/multiqc_report.html"
  else
    echo "NOTE: multiqc 未安装，已跳过 HTML 报告。"
    echo "      安装: conda install -c bioconda multiqc   或  pip install multiqc"
    echo "      TSV 汇总仍在 ${outdir}/"
  fi
fi

echo -e "\n=== QC 完成 ==="
ls -lh "$outdir" | sed -n '1,30p'
